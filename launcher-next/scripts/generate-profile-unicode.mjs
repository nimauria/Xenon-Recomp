// Generate shared data with the build-time Node Unicode version; runtime never depends on Node.
import { writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
process.chdir(fileURLToPath(new URL("../", import.meta.url)));
if (process.versions.unicode !== "17.0")
  throw Error(
    "Use a Node build with Unicode 17.0 to regenerate the pinned profile mapping",
  );
const lower = [],
  space = [];
for (let point = 0; point <= 0x10ffff; point++) {
  if (point >= 0xd800 && point <= 0xdfff) continue;
  const scalar = String.fromCodePoint(point),
    mapped = scalar.toLowerCase();
  if (mapped !== scalar) lower.push([point, mapped]);
  if (/\p{White_Space}/u.test(scalar)) space.push(point);
}
await mkdir("native/third_party/unicode", { recursive: true });
await writeFile(
  "contracts/profile-unicode.json",
  JSON.stringify({
    version: "17.0.0",
    policy:
      "Unconditional lowercase per Unicode scalar; Unicode White_Space trim; no normalization or locale tailoring",
    lower,
    space,
  }) + "\n",
);
const bytes = (value) =>
  [...Buffer.from(value)]
    .map((b) => "\\x" + b.toString(16).padStart(2, "0"))
    .join("");
await writeFile(
  "native/third_party/unicode/profile_unicode.hpp",
  `// Generated by scripts/generate-profile-unicode.mjs. Unicode 17.0.0; see LICENSE.txt.
#pragma once
#include <cstdint>
namespace xenon::launcher_next::unicode_data {
struct Lower { std::uint32_t point; const char *value; };
inline constexpr Lower lower[] = {
${lower.map(([point, value]) => `  {0x${point.toString(16)}, "${bytes(value)}"},`).join("\n")}
};
inline constexpr std::uint32_t space[] = {${space.map((point) => "0x" + point.toString(16)).join(",")}};
}
`,
);
console.log(
  `Generated ${lower.length} lowercase mappings and ${space.length} whitespace scalars`,
);
